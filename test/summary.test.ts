import assert from "node:assert/strict";
import test from "node:test";
import { AppDatabase } from "../src/server/db.js";
import { isCorsOriginAllowed, isKeylessModelUrlAllowed, isLoopbackUrl, isPrivateNetworkUrl } from "../src/server/network.js";
import { formatSummaryMarkdown, summaryFileName } from "../src/server/summary.js";
import type { Agent, Room } from "../src/server/types.js";

const room: Room = {
  id: "room-test",
  slug: "launch-room",
  name: "Launch room",
  projectBrief: "Ship the launch.",
  createdBy: "user-sam",
  createdAt: "2026-11-26T00:00:00.000Z"
};

const agent: Agent = {
  id: "agent-test",
  username: "ai-editor",
  displayName: "Editor",
  provider: "openai",
  baseUrl: "http://127.0.0.1:8788/v1",
  model: "test",
  apiKeyEnv: "",
  systemPrompt: "",
  enabled: true,
  createdBy: "user-sam",
  createdAt: "2026-11-26T00:00:00.000Z"
};

test("summary export wraps clean model Markdown with provenance", () => {
  const markdown = formatSummaryMarkdown(room, agent, "```markdown\n# Duplicate title\n\n## Overview\n\nA factual summary.\n```", "2026-11-26T09:15:00.000Z", 42);
  assert.match(markdown, /^# Launch room - AI discussion summary/);
  assert.match(markdown, /Generated by @ai-editor.*42 messages/);
  assert.match(markdown, /## Overview\n\nA factual summary/);
  assert.doesNotMatch(markdown, /```|Duplicate title/);
  assert.equal(summaryFileName(room, "2026-11-26T09:15:00.000Z"), "launch-room-summary-2026-11-26-0915.md");
});

test("loopback, private LAN, and allowlisted tunnel endpoints can be keyless", () => {
  assert.equal(isLoopbackUrl("http://127.0.0.1:11434/v1"), true);
  assert.equal(isLoopbackUrl("http://localhost:1234/v1"), true);
  assert.equal(isLoopbackUrl("https://models.example.com/v1"), false);
  assert.equal(isPrivateNetworkUrl("http://10.0.0.42:11434/v1"), true);
  assert.equal(isPrivateNetworkUrl("http://172.16.20.7:1234/v1"), true);
  assert.equal(isPrivateNetworkUrl("http://192.168.1.42:11434/v1"), true);
  assert.equal(isPrivateNetworkUrl("http://[fd12:3456::42]:11434/v1"), true);
  assert.equal(isPrivateNetworkUrl("http://172.32.0.1:11434/v1"), false);
  assert.equal(isPrivateNetworkUrl("https://models.example.com/v1"), false);
  assert.equal(isKeylessModelUrlAllowed("https://first-model.ngrok.app/v1", "https://first-model.ngrok.app"), true);
  assert.equal(isKeylessModelUrlAllowed("https://first-model.ngrok.app/v1", "https://other-model.ngrok.app"), false);
  assert.equal(isKeylessModelUrlAllowed("http://first-model.ngrok.app/v1", "http://first-model.ngrok.app"), false);
  assert.equal(isKeylessModelUrlAllowed("https://first-model.ngrok.app/v1", "not-a-url"), false);
  const db = new AppDatabase(":memory:");
  const local = db.addAgent({
    roomId: "room-studio",
    username: "ai-local-test",
    displayName: "Local test",
    provider: "openai",
    baseUrl: "http://127.0.0.1:8788/v1",
    model: "fixture",
    apiKeyEnv: "",
    systemPrompt: "",
    createdBy: "user-sam"
  });
  assert.equal(local.configured, true);
  const lan = db.addAgent({
    roomId: "room-studio",
    username: "ai-lan-test",
    displayName: "LAN test",
    provider: "openai",
    baseUrl: "http://192.168.1.42:11434/v1",
    model: "fixture",
    apiKeyEnv: "",
    systemPrompt: "",
    createdBy: "user-sam"
  });
  assert.equal(lan.configured, true);
  const previousOrigins = process.env.KEYLESS_MODEL_ORIGINS;
  process.env.KEYLESS_MODEL_ORIGINS = "https://first-model.ngrok.app";
  try {
    const tunnel = db.addAgent({
      roomId: "room-studio",
      username: "ai-tunnel-test",
      displayName: "Tunnel test",
      provider: "openai",
      baseUrl: "https://first-model.ngrok.app/v1",
      model: "fixture",
      apiKeyEnv: "",
      systemPrompt: "",
      createdBy: "user-sam"
    });
    assert.equal(tunnel.configured, true);
  } finally {
    if (previousOrigins === undefined) delete process.env.KEYLESS_MODEL_ORIGINS;
    else process.env.KEYLESS_MODEL_ORIGINS = previousOrigins;
  }
  assert.throws(() => db.addAgent({
    roomId: "room-studio",
    username: "ai-remote-test",
    displayName: "Remote test",
    provider: "openai",
    baseUrl: "https://models.example.com/v1",
    model: "fixture",
    apiKeyEnv: "",
    systemPrompt: "",
    createdBy: "user-sam"
  }), /key environment variable is required/i);
  db.close();
});

test("CORS origins support exact, private-network, and deliberate wildcard rules", () => {
  assert.equal(isCorsOriginAllowed("http://localhost:5173", "http://localhost:5173,http://127.0.0.1:5173"), true);
  assert.equal(isCorsOriginAllowed("https://example.com", "http://localhost:5173"), false);
  assert.equal(isCorsOriginAllowed("http://192.168.1.50:5173", "private-network"), true);
  assert.equal(isCorsOriginAllowed("http://10.20.30.40:4173", "private-network"), true);
  assert.equal(isCorsOriginAllowed("https://example.com", "private-network"), false);
  assert.equal(isCorsOriginAllowed("https://example.com", "*"), true);
});
