import type { Agent, Room } from "./types.js";

const cleanModelMarkdown = (value: string): string => {
  const withoutFence = value.trim().replace(/^```(?:markdown|md)?\s*\n?/i, "").replace(/\n?```\s*$/i, "").trim();
  return withoutFence.replace(/^#\s+[^\n]+\n+/, "").trim();
};

export const summaryFileName = (room: Room, generatedAt: string): string => {
  const stamp = generatedAt.slice(0, 16).replace("T", "-").replace(":", "");
  return `${room.slug || "room"}-summary-${stamp}.md`;
};

export const formatSummaryMarkdown = (room: Room, agent: Agent, body: string, generatedAt: string, messageCount: number): string => [
  `# ${room.name} - AI discussion summary`,
  "",
  `> Generated by @${agent.username} on ${generatedAt} from ${messageCount.toLocaleString("en-US")} messages. AI-generated; verify decisions and commitments against the full transcript.`,
  "",
  cleanModelMarkdown(body),
  "",
  "---",
  "",
  "Exported from SamIsip. The complete room transcript remains the source of truth.",
  ""
].join("\n");
