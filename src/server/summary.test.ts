import assert from "node:assert/strict";
import test from "node:test";
import { AppDatabase } from "./db.js";
import { isCorsOriginAllowed, isLoopbackUrl } from "./network.js";
import { formatSummaryMarkdown, summaryFileName } from "./summary.js";
import type { Agent, Room } from "./types.js";

const room: Room = {
  id: "room-test",
  slug: "launch-room",
  name: "Launch room",
  projectBrief: "Ship the launch.",
  createdBy: "user-sam",
  createdAt: "2026-11-26T00:00:00.000Z"
};

const agent: Agent = {
  id: "agent-test",
  username: "ai-editor",
  displayName: "Editor",
  provider: "openai",
  baseUrl: "http://127.0.0.1:8788/v1",
  model: "test",
  apiKeyEnv: "",
  systemPrompt: "",
  enabled: true,
  createdBy: "user-sam",
  createdAt: "2026-11-26T00:00:00.000Z"
};

test("summary export wraps clean model Markdown with provenance", () => {
  const markdown = formatSummaryMarkdown(room, agent, "```markdown\n# Duplicate title\n\n## Overview\n\nA factual summary.\n```", "2026-11-26T09:15:00.000Z", 42);
  assert.match(markdown, /^# Launch room — AI discussion summary/);
  assert.match(markdown, /Generated by @ai-editor.*42 messages/);
  assert.match(markdown, /## Overview\n\nA factual summary/);
  assert.doesNotMatch(markdown, /```|Duplicate title/);
  assert.equal(summaryFileName(room, "2026-11-26T09:15:00.000Z"), "launch-room-summary-2026-11-26-0915.md");
});

test("local endpoints can be keyless while remote endpoints still require a key reference", () => {
  assert.equal(isLoopbackUrl("http://127.0.0.1:11434/v1"), true);
  assert.equal(isLoopbackUrl("http://localhost:1234/v1"), true);
  assert.equal(isLoopbackUrl("https://models.example.com/v1"), false);
  const db = new AppDatabase(":memory:");
  const local = db.addAgent({
    roomId: "room-studio",
    username: "ai-local-test",
    displayName: "Local test",
    provider: "openai",
    baseUrl: "http://127.0.0.1:8788/v1",
    model: "fixture",
    apiKeyEnv: "",
    systemPrompt: "",
    createdBy: "user-sam"
  });
  assert.equal(local.configured, true);
  assert.throws(() => db.addAgent({
    roomId: "room-studio",
    username: "ai-remote-test",
    displayName: "Remote test",
    provider: "openai",
    baseUrl: "https://models.example.com/v1",
    model: "fixture",
    apiKeyEnv: "",
    systemPrompt: "",
    createdBy: "user-sam"
  }), /key environment variable is required/i);
  db.close();
});

test("CORS origins are explicit and support a deliberate wildcard", () => {
  assert.equal(isCorsOriginAllowed("http://localhost:5173", "http://localhost:5173,http://127.0.0.1:5173"), true);
  assert.equal(isCorsOriginAllowed("https://example.com", "http://localhost:5173"), false);
  assert.equal(isCorsOriginAllowed("https://example.com", "*"), true);
});
